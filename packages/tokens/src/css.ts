import type { ThemeDefinition, TokenMap } from "./types.js";

function declarations(tokens: TokenMap, indent = "  "): string {
  return Object.entries(tokens)
    .map(([name, value]) => `${indent}--${name}: ${value};`)
    .join("\n");
}

/**
 * Renders the CSS custom properties for every theme.
 *
 * - The first theme is the default and also applies at `:root`.
 * - Any theme is selected with `data-theme="<name>"` on an ancestor.
 * - Dark mode is the `.dark` class on an ancestor (or the same element),
 *   matching the shadcn/ui and next-themes convention.
 */
export function renderVariablesCss(themes: readonly ThemeDefinition[]): string {
  const blocks = themes.map((theme, index) => {
    const scope = `[data-theme="${theme.name}"]`;
    const lightSelector = index === 0 ? `:root,\n${scope}` : scope;
    const darkSelector =
      index === 0
        ? `.dark,\n${scope}.dark,\n${scope} .dark`
        : `${scope}.dark,\n${scope} .dark,\n.dark ${scope}`;

    return [
      `/* Theme: ${theme.label} */`,
      `${lightSelector} {`,
      declarations(theme.base),
      declarations(theme.light),
      "}",
      "",
      `${darkSelector} {`,
      declarations(theme.dark),
      "}",
    ].join("\n");
  });

  return `/* Generated by @kifiya/tokens. Do not edit. */\n\n${blocks.join("\n\n")}\n`;
}
